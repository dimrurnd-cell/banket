# -*- coding: utf-8 -*-
"""Сборка версии для вставки в Tilda.

Выдаёт по одному HTML-фрагменту на страницу — его целиком вставляют в блок
«T123 · HTML-код». Шапка и подвал выносятся в служебные страницы «Хедер»
и «Футер». Стили и скрипт подключаются один раз в настройках сайта.

    ASSET_BASE=https://example.com/assets/ python3 _src/build_tilda.py

ASSET_BASE — адрес, по которому лежат папки css/, js/ и img/ из assets/.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import build as B  # noqa: E402
from data import SITE  # noqa: E402
import pages as P  # noqa: E402

OUT = os.path.join(ROOT, "tilda")
# Куда залито содержимое assets/. Перебивается переменной окружения.
ASSET_BASE = os.environ.get(
    "ASSET_BASE", "https://donexpocentre.ru/static/banket/assets/").rstrip("/") + "/"
# Стили и скрипт можно держать отдельно от фотографий — и лучше держать.
# Если хранилище с картинками окажется недоступным, страница потеряет
# фотографии; если недоступен адрес со стилями — она рассыплется целиком.
# Поэтому css/ и js/ имеет смысл класть туда, от чего сайт зависит и так.
CODE_BASE = os.environ.get("CODE_BASE", ASSET_BASE).rstrip("/") + "/"
ASSET_ORIGIN = "/".join(ASSET_BASE.split("/")[:3])
CODE_ORIGIN = "/".join(CODE_BASE.split("/")[:3])

# Шрифты лежат рядом с сайтом и подключаются из site.css. Предзагрузку
# намеренно не делаем: замер показал, что она отнимает у кадра первого
# экрана те же ~290 мс, которые выигрывает у первой отрисовки текста,
# а LCP — метрика ранжирования, в отличие от FCP.
FONTS = ""


def absolutise(html):
    """Внутри Tilda относительные пути к ассетам не работают.

    Замена по кавычке пропускала вторых кандидатов в srcset — они отделены
    запятой, а не кавычкой. Ловим начало URL по любому разделителю; re.sub
    не пересматривает собственную подстановку, поэтому уже абсолютные
    адреса (в них тоже есть «/assets/») не портятся.
    """
    html = re.sub(r'(?<=[\s"\'(,])/assets/(css|js)/', CODE_BASE + r"\1/", html)
    return re.sub(r'(?<=[\s"\'(,])/assets/', ASSET_BASE, html)


def slug_of(page):
    u = page["url"].strip("/")
    return u.replace("/", "-") or "glavnaya"


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


def build():
    if os.path.isdir(OUT):
        for root, _, files in os.walk(OUT, topdown=False):
            for f in files:
                os.remove(os.path.join(root, f))
            os.rmdir(root)

    # ---------- глобальный код ------------------------------------------
    # Всё в один HEAD: поле «HTML-код перед </body>» есть не на каждом тарифе.
    # Tilda вставляет этот код сразу после <head>, то есть свои стили она
    # подключит после наших. Ничего не ломается: правила совместимости в
    # site.css написаны селекторами из трёх элементов и выигрывают у «*»
    # независимо от порядка подключения. Проверено сравнением вычисленных
    # стилей со статической сборкой — расхождений нет.
    write(os.path.join(OUT, "_global", "head-code.html"), absolutise(
        '<!-- Настройки сайта → Ещё → HTML-код для вставки внутрь HEAD -->\n'
        '%s'
        '%s'
        '%s'
        '<link rel="stylesheet" href="/assets/css/site.css?v=4">\n'
        '<script src="/assets/js/site.js?v=4" defer></script>\n'
        '<meta name="theme-color" content="#0B181C">\n' % (
            "".join('<link rel="preconnect" href="%s" crossorigin>\n' % o
                    for o in dict.fromkeys([CODE_ORIGIN, ASSET_ORIGIN])),
            B.CDN_PRECONNECT, FONTS)))

    # Тот же CSS одним куском — на случай, если стили решат не тянуть с CDN,
    # а вставить в «Настройки сайта → Ещё → Пользовательские CSS-стили».
    # Файл самодостаточен: единственный url() внутри — data-URI.
    with open(os.path.join(ROOT, "assets", "css", "site.css"), encoding="utf-8") as fh:
        write(os.path.join(OUT, "_global", "custom-css.css"),
              "/* Настройки сайта → Ещё → Пользовательские CSS-стили.\n"
              "   Альтернатива строке <link> в HEAD: тогда оформление не\n"
              "   зависит от стороннего адреса вообще. */\n" + fh.read())

    write(os.path.join(OUT, "_global", "header-block.html"), absolutise(
        '<!-- Страница «Хедер» → блок T123 «HTML-код» -->\n'
        '<div class="bn5-root">\n%s\n%s\n</div>\n'
        % (B.render_header(""), B.render_mobile_nav())))

    write(os.path.join(OUT, "_global", "footer-block.html"), absolutise(
        '<!-- Страница «Футер» → блок T123 «HTML-код».\n'
        '     Формы здесь нет: её даёт штатный блок формы Tilda, который\n'
        '     ставится ВЫШЕ этого блока. У того блока должен быть\n'
        '     ID блока для ссылки = zayavka, иначе кнопки «Проверить дату»\n'
        '     по всему сайту будут вести в никуда. -->\n'
        '<div class="bn5-root">\n%s\n</div>\n' % B.render_chrome(include_form=False)))

    # ---------- страницы -------------------------------------------------
    rows = []
    for p in P.PAGES:
        B.seed_page_images(p)
        body = "\n".join(B.RENDER[s["t"]](s) for s in p["sections"])
        block = '<div class="bn5-root">\n%s\n</div>\n' % body
        block = re.sub(r"\n{3,}", "\n\n", absolutise(block))

        slug = slug_of(p)
        write(os.path.join(OUT, slug, "block.html"), block)

        url = p["url"] if p["url"] != "/" else "/"
        og = p.get("og") or B.COVERS["hero"]
        if og.startswith("/assets/"):
            og = absolutise('"' + og)[1:]
        elif og.startswith("/"):
            og = SITE["origin"] + og
        write(os.path.join(OUT, slug, "seo.txt"),
              "Настройки страницы в Tilda\n"
              "==========================\n\n"
              "Адрес страницы (URL):  %s\n"
              "Заголовок (Title):     %s\n"
              "Описание (Description):%s\n"
              "Картинка для соцсетей: %s\n" % (url, p["title"], " " + p["desc"], og))

        rows.append((url, p["title"], slug, len(p["sections"]), len(block)))

    # ---------- инструкция ----------------------------------------------
    table = "\n".join(
        "| `%s` | %s | %s | %.0f КБ |" % (u, s, sl, ln / 1024.0)
        for u, s, sl, _, ln in
        [(u, (t[:44] + "…") if len(t) > 45 else t, sl, n, ln) for u, t, sl, n, ln in rows])
    write(os.path.join(OUT, "README.md"), README % {
        "count": len(rows), "table": table, "asset_base": ASSET_BASE, "fonts": FONTS})

    leftovers = []
    for root, _, files in os.walk(OUT):
        for f in files:
            if not f.endswith(".html"):
                continue
            path = os.path.join(root, f)
            with open(path, encoding="utf-8") as fh:
                for m in re.finditer(r'(?<=[\s"\'(,])/assets/\S*', fh.read()):
                    leftovers.append("%s: %s" % (os.path.relpath(path, OUT), m.group(0)[:70]))
    if leftovers:
        raise SystemExit("остались относительные пути к ассетам:\n  " + "\n  ".join(leftovers))

    print("готово: %d страниц в tilda/, относительных путей к ассетам нет" % len(rows))
    if CODE_BASE != ASSET_BASE:
        print("CODE_BASE  = %s   (стили и скрипт)" % CODE_BASE)
    print("ASSET_BASE = %s" % ASSET_BASE)


